# -*- coding: utf-8 -*-
"""model.json -> native/chart_data.inc (표시 모델) + native/code_hashes.inc (명령부 해시).

C++ 문자열은 \\u 이스케이프로 적어 인코딩 사고를 피한다.
"""
import json, os, re

ROOT = r'P:\AI\forest-flowchart-claude'
M = json.load(open(os.path.join(ROOT, 'data', 'model.json'), encoding='utf-8'))
OUT = os.path.join(ROOT, 'native')

KIND = {'choice': 0, 'back': 1, 'end': 2, 'restart': 3, 'stop': 4}
TAG = {'random': 1, 'cond': 2, 'late': 4, 'nav': 8}
SKIND = {'story': 0, 'main': 1, 'sub': 2}


def w(s):
    out = []
    for ch in s:
        o = ord(ch)
        if 32 <= o < 127 and ch not in '"\\':
            out.append(ch)
        elif o > 0xFFFF:
            raise ValueError(s)
        else:
            out.append('\\u%04x' % o)
    return 'L"' + ''.join(out) + '"'


def f(x):
    return '%.1ff' % x


chap_idx = {c['id']: i for i, c in enumerate(M['chapters'])}
scene_ids = []
for c in M['chapters']:
    for s in c['scenes']:
        if s in M['scenes'] and s not in scene_ids:
            scene_ids.append(s)
for s in M['scenes']:
    if s not in scene_ids:
        scene_ids.append(s)          # 곁가지 장면(배치 없음)
scene_idx = {s: i for i, s in enumerate(scene_ids)}
choice_ids = []
for p in M['pages']:
    for cl in p['clusters']:
        for cid in sorted(cl['pos'], key=lambda k: M['choices'][k]['kpc']):
            choice_ids.append(cid)
assert set(choice_ids) == set(M['choices']), (len(choice_ids), len(M['choices']))
choice_idx = {c: i for i, c in enumerate(choice_ids)}
page_of = {}
rect_of = {}
cluster_of = {}
for pi, p in enumerate(M['pages']):
    for sid, r in p['strip'].items():
        page_of[sid] = pi
        rect_of[('s', sid)] = r
    for ci, cl in enumerate(p['clusters']):
        for cid, r in cl['pos'].items():
            rect_of[('c', cid)] = r
            cluster_of[cid] = (pi, ci)

L = []
L.append('// Generated by tools/gen_cpp.py from data/model.json. Do not edit.')
L.append('const int kChapterCount=%d;' % len(M['chapters']))
L.append('const ChapterDef kChapters[]={')
for c in M['chapters']:
    p = [pp for pp in M['pages'] if pp['chapter'] == c['id']][0]
    order = ','.join(str(scene_idx[s]) for s in p['order'])
    L.append('{%s,%s,%s,%s,{%s},%d},' % (w(c['id']), w(c['title']), f(p['size'][0]), f(p['size'][1]), order,
                                        {'III': 1, 'V': 1, 'VI': 1}.get(c['id'], 0)))
L.append('};')

L.append('const std::vector<SceneDisp> kScenes={')
for sid in scene_ids:
    s = M['scenes'][sid]
    r = rect_of.get(('s', sid), [0, 0, 0, 0])
    parent = scene_idx.get(s.get('parent')) if s.get('parent') else -1
    L.append('{%d,%d,%s,%d,%s,%s,%s,%s,{%s},{%s},%d,%d},' % (
        int(sid), chap_idx[s['chapter']], w(s['title']), SKIND[s['kind']],
        f(r[0]), f(r[1]), f(r[2]), f(r[3]),
        ','.join(str(x) for x in s['slots']), ','.join(str(x) for x in s['exit_slots']),
        page_of.get(sid, -1), parent if parent is not None else -1))
L.append('};')


def wits(lst):
    return '{' + ','.join('{%d,%d}' % (int(a), b) for a, b in lst) + '}'


L.append('const std::vector<ChoiceDisp> kChoices={')
for cid in choice_ids:
    c = M['choices'][cid]
    r = rect_of[('c', cid)]
    pi, ci = cluster_of[cid]
    opts = []
    for o in c['options']:
        outs = []
        for oc in o['outs']:
            t = choice_idx.get(oc.get('node'), -1) if oc['k'] in ('choice', 'back') else -1
            outs.append('{%d,%d}' % (KIND[oc['k']], t))
        tags = sum(TAG[t] for t in o['tags'])
        src = o.get('src', [cid, o['idx']])
        sig = '{' + ','.join('{%d,%d}' % (v, val) for v, val in o.get('sig', [])) + '}'
        opts.append('{%s,%d,%s,{%s},%d,"%s",%d,%s}' % (w(o['label']), o['slot'], wits(o['witness']), ','.join(outs), tags, src[0], src[1], sig))
    preds = ','.join('{%d,%d}' % (choice_idx[a], b - 1) for a, b in c['preds'] if a in choice_idx)
    pages = ','.join('"%s"' % x for x in c.get('page_ids', [cid]))
    L.append('{"%s",%d,%d,%d,%s,%d,%s,%s,%s,%s,{%s},%s,%s,{%s},{%s},%d,%d},' % (
        cid, int(c['script']), chap_idx[c['chapter']], scene_idx[c['script']], w(c['question']), c['q_slot'],
        f(r[0]), f(r[1]), f(r[2]), f(r[3]),
        ','.join(opts), wits(c.get('reach', [])), wits(c.get('pre', [])), preds, pages, pi, ci))
L.append('};')

L.append('const std::vector<ClusterDisp> kClusters={')
for pi, p in enumerate(M['pages']):
    for ci, cl in enumerate(p['clusters']):
        back = ','.join('{%d,%d}' % (choice_idx[a], choice_idx[b]) for a, b in cl['back'])
        L.append('{%d,%d,%d,%d,{%s}},' % (pi, ci, scene_idx[cl['scene']], 1 if cl['anchor'] == 'right' else 0, back))
L.append('};')
L.append('const float kQH=%s,kLH=%s;' % (f(M['sizes']['q_h']), f(M['sizes']['l_h'])))
open(os.path.join(OUT, 'chart_data.inc'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')

H = ['// Generated by tools/gen_cpp.py: SHA-256 of each script\'s command section (strings excluded).',
     'struct CodeHash {int script;const char* sha;};',
     'const CodeHash kCodeHashes[]={']
for sid, h in sorted(M['code_sha256'].items()):
    if sid in ('0001',):
        continue                       # 타이틀은 차트 단추를 끼워 넣는다
    H.append('{%d,"%s"},' % (int(sid), h))
H.append('};')
open(os.path.join(OUT, 'code_hashes.inc'), 'w', encoding='utf-8').write('\n'.join(H) + '\n')
print('scenes', len(scene_ids), 'choices', len(choice_ids), 'pages', len(M['pages']))
